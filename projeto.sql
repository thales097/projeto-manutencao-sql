--- CRIANDO AS TABELAS---
CREATE TABLE EQUIPAMENTO(
	ID_EQUIPAMENTO SERIAL PRIMARY KEY,
	NOME_EQUIPAMENTO VARCHAR (50) NOT NULL,
	TIPO_EQUIPAMENTO VARCHAR (50) NOT NULL,
	DATA_AQUISICAO DATE NOT NULL,
	SETOR VARCHAR (50) NOT NULL,
	STATUS VARCHAR (50) NOT NULL
);

CREATE TABLE TECNICO(
	ID_TECNICO SERIAL PRIMARY KEY,
	NOME VARCHAR (50) NOT NULL,
	ESPECIALIDADE VARCHAR (50) NOT NULL,
	TELEFONE VARCHAR (11) NOT NULL,
	DATA_ADMISSAO DATE NOT NULL
);

CREATE TABLE TIPO_MANUTENCAO(
	ID_TIPO SERIAL PRIMARY KEY,
	NOME_TIPO VARCHAR (50) NOT NULL,
	DESCRICAO VARCHAR (50) NOT NULL,
	TEMPO_ESTIMADO INT NOT NULL
);

CREATE TABLE ORDEM_MANUTENCAO(
	ID_ORDEM SERIAL PRIMARY KEY,
	DATA_ABERTURA DATE NOT NULL,
	DATA_ENCERRAMENTO DATE NOT NULL,
	PRIORIDADE VARCHAR (50) NOT NULL,
	STATUS VARCHAR (50) NOT NULL
);

CREATE TABLE SERVICAO_EXECUTADO(
	ID_SERVICO SERIAL PRIMARY KEY,
	DATA_EXECUCAO DATE NOT NULL,
	DESCRICAO_SERVICO VARCHAR (50) NOT NULL,
	HORAS_TRABALHADAS INT NOT NULL,
	CUSTO_MATERIAL NUMERIC (10,2) NOT NULL,
	CUSTO_MAO_OBRA NUMERIC (10,2) NOT NULL,
	ID_TECNICO INT NOT NULL REFERENCES TECNICO,
	ID_ORDEM INT NOT NULL REFERENCES ORDEM_MANUTENCAO
);

